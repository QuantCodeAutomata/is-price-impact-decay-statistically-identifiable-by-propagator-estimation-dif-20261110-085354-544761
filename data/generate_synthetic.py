"""Synthetic data generation for the SFK null-model experiments.

Both selected experiments use only synthetic data generated by the SFK
model (paper Part II); no market data is required. This module is the single
entry point experiments and tests use to obtain simulated sample paths; the
model dynamics themselves live in src/sfk_model.py.
"""

from __future__ import annotations

from collections.abc import Iterator

import numpy as np

from src.sfk_model import SFKSimulation, simulate_sfk


def generate_sfk_sample(
    alpha: float,
    delta: float,
    n_steps: int,
    seed: int,
    m_splitters: int = 1,
) -> SFKSimulation:
    """Generate one SFK sample path for the given parameters and seed.

    Args:
        alpha: Metaorder-size distribution exponent, alpha in (1, 2).
        delta: Price-impact exponent, I(Q) = Q^delta.
        n_steps: Number of simulation steps (child orders).
        seed: Seed for the NumPy random generator controlling this draw.
        m_splitters: Number of metaorder splitters M (only M = 1 supported).

    Returns:
        An SFKSimulation sample path.
    """
    rng = np.random.default_rng(seed)
    return simulate_sfk(alpha=alpha, delta=delta, n_steps=n_steps, rng=rng, m_splitters=m_splitters)


def generate_sfk_samples(
    alpha: float,
    delta: float,
    n_steps: int,
    n_seeds: int,
    base_seed: int,
    m_splitters: int = 1,
) -> list[SFKSimulation]:
    """Generate n_seeds independent SFK sample paths for Monte Carlo averaging."""
    return [
        generate_sfk_sample(
            alpha=alpha,
            delta=delta,
            n_steps=n_steps,
            seed=base_seed + i,
            m_splitters=m_splitters,
        )
        for i in range(n_seeds)
    ]


def iter_sfk_samples(
    alpha: float,
    delta: float,
    n_steps: int,
    n_seeds: int,
    base_seed: int,
    m_splitters: int = 1,
) -> Iterator[SFKSimulation]:
    """Yield n_seeds independent SFK sample paths one at a time.

    Same draws as generate_sfk_samples (seeds base_seed, ..., base_seed +
    n_seeds - 1) but without holding more than one sample path in memory at
    once, for Monte Carlo averages over long, memory-heavy simulations
    (paper's suggested length of up to 10^7 steps per path, Sec. "SFK model
    as a null model").
    """
    for i in range(n_seeds):
        yield generate_sfk_sample(
            alpha=alpha,
            delta=delta,
            n_steps=n_steps,
            seed=base_seed + i,
            m_splitters=m_splitters,
        )
