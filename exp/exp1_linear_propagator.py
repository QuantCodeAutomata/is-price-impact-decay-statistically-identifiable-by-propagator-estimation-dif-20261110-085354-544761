"""Experiment 1: linear propagator deconvolution applied to the SFK null model.

Reproduces the paper's Fig. 2: the standard linear propagator deconvolution
(Eqs. 4a-4c) is applied to synthetic order-sign and price series generated by
the SFK model (Part II, Sec. V) with a single metaorder splitter (M = 1),
strictly permanent square-root impact (delta = 1/2, Eq. 10), and metaorder
sizes drawn from the power-law distribution psi(L) propto L^{-alpha-1}
(Eq. 399), for alpha in {1.25, 1.5, 1.75}.

For each alpha the script estimates C(tau), S(tau) and the inferred
propagator G(tau), fits their power-law tails on log-log axes, and compares
the fitted exponents with the paper's predictions:

    C(tau) ~ tau^{-gamma},        gamma = alpha - 1
    S(tau) ~ tau^{delta - alpha}
    G(tau) ~ tau^{-beta_c},       beta_c = (1 - gamma) / 2

even though the SFK model's true impact never decays (Sec. "Universal decay
theorems"). Outputs (plots, summary table, log) are written to results/.
"""

from __future__ import annotations

import json
import logging
import time

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from data.generate_synthetic import iter_sfk_samples
from src import config
from src.exact_sfk_formulas import exact_autocorrelation, exact_response_increment
from src.powerlaw_fit import fit_power_law
from src.propagator_estimation import estimate_linear_propagator_mc_streaming

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

RESULTS_DIR = "results"


def _plot_decay(
    tau: np.ndarray,
    y: np.ndarray,
    fit_exponent: float,
    fit_amplitude: float,
    theory_exponent: float,
    label: str,
    title: str,
    path: str,
) -> None:
    """Log-log plot of one statistic against tau with its fitted and
    theoretical power laws overlaid."""
    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    positive = (tau > 0) & (np.abs(y) > 0)
    ax.loglog(tau[positive], np.abs(y[positive]), ".", color="tab:blue", label=f"|{label}(tau)|")
    tail = tau[positive]
    ax.loglog(
        tail,
        fit_amplitude * tail**fit_exponent,
        "-",
        color="tab:red",
        label=f"fit: exponent={fit_exponent:.3f}",
    )
    ax.loglog(
        tail,
        np.abs(y[positive][0]) * (tail / tail[0]) ** theory_exponent,
        "--",
        color="black",
        label=f"theory: exponent={theory_exponent:.3f}",
    )
    ax.set_xlabel("tau")
    ax.set_ylabel(f"|{label}(tau)|")
    ax.set_title(title)
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def run_experiment(n_steps: int, n_seeds: int, max_lag: int, wh_truncation: int) -> dict:
    """Run the linear propagator deconvolution for every alpha in EXP1_ALPHAS.

    Returns a dict keyed by alpha with the fitted vs. theoretical exponents
    and the diagnostic G_infty (propagator value at the largest estimated
    lag, which the universal decay theorems predict to vanish).
    """
    summary: dict = {}
    for alpha in config.EXP1_ALPHAS:
        gamma_theory = alpha - 1.0
        s_exponent_theory = config.IMPACT_EXPONENT_DELTA - alpha
        beta_c_theory = (1.0 - gamma_theory) / 2.0

        t0 = time.time()
        simulations = iter_sfk_samples(
            alpha=alpha,
            delta=config.IMPACT_EXPONENT_DELTA,
            n_steps=n_steps,
            n_seeds=n_seeds,
            base_seed=config.EXP1_RANDOM_SEED,
            m_splitters=config.M_SPLITTERS,
        )
        result = estimate_linear_propagator_mc_streaming(
            simulations, max_lag=max_lag, wh_truncation=wh_truncation
        )
        elapsed = time.time() - t0
        logger.info(
            "alpha=%.2f: simulated %d seeds x %d steps, max_lag=%d in %.1fs",
            alpha, n_seeds, n_steps, max_lag, elapsed,
        )

        c_fit = fit_power_law(
            result.lags, result.autocorrelation, config.EXP1_FIT_TAU_MIN, config.EXP1_FIT_TAU_MAX
        )
        s_fit = fit_power_law(
            result.lags, result.response_increment, config.EXP1_FIT_TAU_MIN, config.EXP1_FIT_TAU_MAX
        )
        g_valid = ~np.isnan(result.propagator)
        g_tau_max = min(config.EXP1_FIT_TAU_MAX, int(result.lags[g_valid].max()) - 1)
        g_fit = fit_power_law(
            result.lags, result.propagator, config.EXP1_FIT_TAU_MIN, g_tau_max
        )

        g_infty_estimate = float(
            np.nanmean(result.propagator[g_valid][-max(1, max_lag // 20) :])
        )

        # Independent cross-check against the exact SFK formulas (Eqs. 400,
        # 408-409) for M = 1, over a short lag range (the integrals are slow).
        n_max_exact = config.EXP1_EXACT_VERIFICATION_N_MAX
        exact_c = exact_autocorrelation(alpha, n_max_exact)
        exact_s = exact_response_increment(alpha, config.IMPACT_EXPONENT_DELTA, n_max_exact)
        exact_check_lags = np.arange(1, n_max_exact + 1)
        c_rel_err = float(
            np.mean(
                np.abs(result.autocorrelation[1 : n_max_exact + 1] - exact_c[1:])
                / np.abs(exact_c[1:])
            )
        )
        s_rel_err = float(
            np.mean(
                np.abs(result.response_increment[1 : n_max_exact + 1] - exact_s[1:])
                / np.abs(exact_s[1:])
            )
        )

        for name, y, fit in (
            ("C", result.autocorrelation, c_fit),
            ("S", result.response_increment, s_fit),
            ("G", result.propagator, g_fit),
        ):
            theory = {"C": -gamma_theory, "S": s_exponent_theory, "G": -beta_c_theory}[name]
            _plot_decay(
                result.lags,
                y,
                fit.exponent,
                fit.amplitude,
                theory,
                name,
                f"alpha={alpha}: {name}(tau)",
                f"{RESULTS_DIR}/exp1_alpha{alpha}_{name}.png",
            )

        summary[str(alpha)] = {
            "alpha": alpha,
            "gamma_theory": gamma_theory,
            "gamma_fit": -c_fit.exponent,
            "s_exponent_theory": s_exponent_theory,
            "s_exponent_fit": s_fit.exponent,
            "beta_c_theory": beta_c_theory,
            "beta_c_fit": -g_fit.exponent,
            "g_infty_estimate": g_infty_estimate,
            "c_fit_r2": c_fit.r_value**2,
            "s_fit_r2": s_fit.r_value**2,
            "g_fit_r2": g_fit.r_value**2,
            "exact_check_mean_rel_error_C": c_rel_err,
            "exact_check_mean_rel_error_S": s_rel_err,
            "n_steps": n_steps,
            "n_seeds": n_seeds,
            "max_lag": max_lag,
            "elapsed_seconds": elapsed,
        }
        np.savez(
            f"{RESULTS_DIR}/exp1_alpha{alpha}_curves.npz",
            lags=result.lags,
            autocorrelation=result.autocorrelation,
            response_increment=result.response_increment,
            propagator=result.propagator,
            exact_check_lags=exact_check_lags,
            exact_autocorrelation=exact_c[1:],
            exact_response_increment=exact_s[1:],
        )

    return summary


def main(full: bool = False) -> dict:
    n_steps = config.EXP1_N_STEPS_PAPER if full else config.EXP1_N_STEPS_RUN
    n_seeds = config.EXP1_N_SEEDS_PAPER if full else config.EXP1_N_SEEDS_RUN
    logger.info(
        "exp1: realized configuration alphas=%s n_steps=%d n_seeds=%d max_lag=%d",
        config.EXP1_ALPHAS, n_steps, n_seeds, config.EXP1_MAX_LAG,
    )
    summary = run_experiment(n_steps, n_seeds, config.EXP1_MAX_LAG, config.EXP1_WH_TRUNCATION)
    with open(f"{RESULTS_DIR}/exp1_summary.json", "w") as f:
        json.dump(summary, f, indent=2)
    logger.info("exp1: summary written to %s/exp1_summary.json", RESULTS_DIR)
    return summary


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--full", action="store_true", help="Use the paper-scale configuration explicitly"
    )
    args = parser.parse_args()
    main(full=args.full)
